// Builds public/css/abyss.css: the "Abyss" colours (deep blue, teal light) on the classic layout.
// Every rule of forge.css and classic.css that carries a warm colour is repeated under
// :root[data-palette="abyss"], loaded after them, with the colour moved to the sea: dark browns become
// navy, embers and orange become teal; gold titles, reds (errors, badges) and greens stay as they are.
//   node scripts/make-abyss.cjs   (run again after changing forge.css or classic.css)
const fs = require('node:fs');
const path = require('node:path');
const css = path.join(__dirname, '..', 'public', 'css');

function rgbToHsl(r, g, b) {
  r /= 255; g /= 255; b /= 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2;
  if (max === min) return [0, 0, l];
  const d = max - min, s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
  const h = max === r ? (g - b) / d + (g < b ? 6 : 0) : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
  return [h * 60, s, l];
}
function hslToRgb(h, s, l) {
  const k = n => (n + h / 30) % 12, a = s * Math.min(l, 1 - l);
  const f = n => Math.round(255 * (l - a * Math.max(-1, Math.min(k(n) - 3, 9 - k(n), 1))));
  return [f(0), f(8), f(4)];
}
// The sea version of one colour, or null when it stays.
function sea(r, g, b) {
  const [h, s, l] = rgbToHsl(r, g, b);
  if (s < 0.08) return null; // greys, black, white
  if (h < 12 || h > 330 || (h > 80 && h < 330)) return null; // reds, greens, blues
  if (l < 0.3) return hslToRgb(203, Math.min(1, s * 1.1), l * 1.05); // leather, smoke -> deep navy
  if (h >= 36 && h <= 52) return null; // old gold: kept, it is the gold of the crest
  return hslToRgb(h + 148, s, Math.min(0.8, l * 1.02)); // embers, orange -> teal light
}
const hex = value => '#' + value.map(n => n.toString(16).padStart(2, '0')).join('');
function recolor(text) {
  let changed = false;
  const out = text
    .replace(/#([0-9a-f]{6}|[0-9a-f]{3})\b/gi, (m, v) => {
      const full = v.length === 3 ? v.split('').map(c => c + c).join('') : v;
      const next = sea(parseInt(full.slice(0, 2), 16), parseInt(full.slice(2, 4), 16), parseInt(full.slice(4, 6), 16));
      if (!next) return m;
      changed = true;
      return hex(next);
    })
    .replace(/rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(,\s*[\d.]+\s*)?\)/g, (m, r, g, b, a) => {
      const next = sea(+r, +g, +b);
      if (!next) return m;
      changed = true;
      return a ? `rgba(${next.join(', ')}${a})` : `rgb(${next.join(', ')})`;
    });
  return changed ? out : null;
}

// A small CSS reader: top-level rules and one level of @media.
function rules(text) {
  const out = [];
  text = text.replace(/\/\*[\s\S]*?\*\//g, '');
  let i = 0;
  while (i < text.length) {
    const open = text.indexOf('{', i);
    if (open < 0) break;
    const head = text.slice(i, open).trim();
    if (head.startsWith('@')) {
      let depth = 1, j = open + 1;
      while (depth && j < text.length) { if (text[j] === '{') depth++; else if (text[j] === '}') depth--; j++; }
      if (/^@media/.test(head)) out.push({ media: head, inner: rules(text.slice(open + 1, j - 1)) });
      i = j;
      continue;
    }
    const close = text.indexOf('}', open);
    out.push({ selector: head, body: text.slice(open + 1, close).trim() });
    i = close + 1;
  }
  return out;
}
const prefix = selector => selector.split(/,(?![^(]*\))/).map(part => {
  part = part.trim();
  if (part.startsWith(':root')) return part.replace(/^:root/, ':root[data-palette="abyss"]');
  return `:root[data-palette="abyss"] ${part}`;
}).join(', ');
function emit(list) {
  const lines = [];
  for (const rule of list) {
    if (rule.media) { const inner = emit(rule.inner); if (inner.length) lines.push(`${rule.media} {`, ...inner.map(l => '  ' + l), '}'); continue; }
    const decls = rule.body.split(/;(?![^(]*\))/).map(d => d.trim()).filter(Boolean).map(d => recolor(d)).filter(Boolean);
    if (decls.length) lines.push(`${prefix(rule.selector)} { ${decls.join('; ')}; }`);
  }
  return lines;
}

const header = `/* Generated by scripts/make-abyss.cjs from forge.css and classic.css: do not edit by hand.
   "Abyss": the classic layout in deep water colours (navy, teal light, the gold of the crest). */`;
const body = ['forge.css', 'classic.css'].flatMap(name => emit(rules(fs.readFileSync(path.join(css, name), 'utf8'))));
