'use strict';
// Copies the open-licensed fonts (SIL OFL) from node_modules into public/assets/fonts and
// writes public/css/fonts.css. Each alphabet is its own file: the page only downloads what it shows.
const fs = require('node:fs');
const path = require('node:path');

const RANGES = {
  latin: 'U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD',
  'latin-ext': 'U+0100-02BA, U+02BD-02C5, U+02C7-02CC, U+02CE-02D7, U+02DD-02FF, U+0304, U+0308, U+0329, U+1D00-1DBF, U+1E00-1E9F, U+1EF2-1EFF, U+2020, U+20A0-20AB, U+20AD-20C0, U+2113, U+2C60-2C7F, U+A720-A7FF',
  cyrillic: 'U+0301, U+0400-045F, U+0490-0491, U+04B0-04B1, U+2116',
};

// [css family, package, file prefix, subsets, weights, italic weights]
const FAMILIES = [
  ['Inter', 'inter', 'inter', ['latin', 'latin-ext', 'cyrillic'], [400, 500, 600, 700], []],
  ['Cinzel', 'cinzel', 'cinzel', ['latin'], [600, 700], []],
  ['JetBrains Mono', 'jetbrains-mono', 'jetbrains-mono', ['latin'], [400, 600], []],
];

const root = path.join(__dirname, '..');
const target = path.join(root, 'public/assets/fonts');
fs.rmSync(target, { recursive: true, force: true });
fs.mkdirSync(target, { recursive: true });
const css = ['/* Generated by scripts/copy-fonts.cjs - SIL Open Font License fonts from @fontsource. */'];
let count = 0;
for (const [family, pkg, prefix, subsets, weights, italics] of FAMILIES) {
  const variants = [...weights.map(weight => [weight, 'normal']), ...italics.map(weight => [weight, 'italic'])];
  for (const [weight, style] of variants) {
    for (const subset of subsets) {
      const name = `${prefix}-${subset}-${weight}-${style}.woff2`;
      const source = require.resolve(`@fontsource/${pkg}/files/${name}`, { paths: [root] });
      fs.copyFileSync(source, path.join(target, name));
      css.push(`@font-face { font-family: '${family}'; font-style: ${style}; font-weight: ${weight}; font-display: swap; src: url('../assets/fonts/${name}') format('woff2'); unicode-range: ${RANGES[subset]}; }`);
      count++;
    }
  }
}
fs.writeFileSync(path.join(root, 'public/css/fonts.css'), css.join('\n') + '\n');
console.log(`${count} font files copied, public/css/fonts.css written`);
